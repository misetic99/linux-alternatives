// Pure planning logic for the switch planner. No DOM access, so it can be unit tested.
"use strict";

globalThis.PlanCore = (() => {
  const FIT_RANK = { full: 0, good: 1, partial: 2, minimal: 3 };
  const SAFE_REF = /^[A-Za-z0-9][A-Za-z0-9._+-]*$/;
  const INSTALL_CMD = {
    apt: (r) => `sudo apt install ${r}`,
    dnf: (r) => `sudo dnf install ${r}`,
    pacman: (r) => `sudo pacman -S ${r}`,
    snap: (r) => `sudo snap install ${r}`,
  };

  /** One printable line of plain text: safe to put in a shell comment. */
  function clean(value) {
    return String(value ?? "").replace(/[^\x20-\x7E]/g, " ").replace(/\s+/g, " ").trim().slice(0, 80);
  }

  /** Best alternative first: higher fit, then the one with a Flatpak. */
  function rankAlternatives(app) {
    return [...app.alternatives].sort((a, b) => {
      const byFit = (FIT_RANK[a.fit] ?? 9) - (FIT_RANK[b.fit] ?? 9);
      if (byFit) return byFit;
      return Number(hasFlatpak(b.alternative)) - Number(hasFlatpak(a.alternative));
    });
  }

  function flatpakRef(alt) {
    const hit = ((alt && alt.install) || []).find((i) => i.method === "flatpak" && SAFE_REF.test(i.ref));
    return hit ? hit.ref : null;
  }
  const hasFlatpak = (alt) => flatpakRef(alt) !== null;

  /** Build the plan for the selected app ids. Unknown ids are ignored. */
  function buildPlan(apps, ids) {
    const wanted = new Set(ids);
    const items = apps.filter((a) => wanted.has(a.id)).map((app) => {
      const ranked = rankAlternatives(app);
      return { app, primary: ranked[0] || null, others: ranked.slice(1) };
    });
    const covered = items.filter((i) => i.primary).length;
    const counts = { full: 0, good: 0, partial: 0, minimal: 0, none: 0 };
    for (const i of items) counts[i.primary ? i.primary.fit : "none"] += 1;
    return {
      items,
      total: items.length,
      covered,
      counts,
      unverified: items.filter((i) => !i.app.verified).length,
    };
  }

  /** A bash script with one Flatpak install per distinct alternative. */
  function buildScript(plan) {
    const lines = [
      "#!/usr/bin/env bash",
      "# Generated by linux-alternatives. Review every line before running it.",
      "set -euo pipefail",
      "",
      "flatpak remote-add --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo",
      "",
    ];
    const seen = new Set();
    let installs = 0;
    for (const { app, primary } of plan.items) {
      if (!primary) {
        lines.push(`# ${clean(app.name)}: no known alternative yet`);
        continue;
      }
      const alt = primary.alternative;
      lines.push(`# ${clean(app.name)} -> ${clean(alt.name)} (${clean(primary.fit)} fit)`);
      const ref = flatpakRef(alt);
      if (ref) {
        if (!seen.has(ref)) {
          seen.add(ref);
          lines.push(`flatpak install -y flathub ${ref}`);
          installs += 1;
        }
        continue;
      }
      const other = (alt.install || []).find((i) => INSTALL_CMD[i.method] && SAFE_REF.test(i.ref));
      lines.push(other
        ? `# no Flatpak listed; alternative install: ${INSTALL_CMD[other.method](other.ref)}`
        : "# no safe install command listed; see the project homepage");
    }
    if (installs === 0) lines.push("", "# Nothing to install with Flatpak for this selection.");
    return lines.join("\n") + "\n";
  }

  /** Read app ids from a URL hash such as "#apps=autocad,winrar". */
  function parseHash(hash, knownIds) {
    const match = /(?:^|[#&])apps=([^&]*)/.exec(String(hash || ""));
    if (!match) return [];
    const known = new Set(knownIds);
    return [...new Set(match[1].split(",").map((s) => s.trim()).filter((s) => known.has(s)))];
  }

  function toHash(ids) {
    return ids.length ? `#apps=${[...ids].sort().join(",")}` : "";
  }

  return { buildPlan, buildScript, parseHash, toHash, rankAlternatives, clean, SAFE_REF };
})();
